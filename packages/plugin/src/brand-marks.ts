/**
 * The Nectenda mark and wordmark, drawn in code.
 *
 * Built rather than shipped as .svg files for two reasons that both bite
 * silently: the plugin bundler has no loader for an imported asset, and the
 * packaging step copies a fixed list of non-TypeScript files, so a new .svg
 * would simply not be there. Every .ts file under src/ travels on its own.
 *
 * Both take their colour from the surrounding surface, so one copy serves the
 * light theme and the dark one.
 */

const SVG_NS = 'http://www.w3.org/2000/svg';

function svg(viewBox: string, width: number, height: number, cls: string): SVGSVGElement {
  const el = document.createElementNS(SVG_NS, 'svg');
  el.setAttribute('viewBox', viewBox);
  el.setAttribute('width', String(width));
  el.setAttribute('height', String(height));
  el.setAttribute('aria-hidden', 'true');
  el.classList.add(cls);
  return el;
}

function path(d: string, attrs: Record<string, string>): SVGPathElement {
  const el = document.createElementNS(SVG_NS, 'path');
  el.setAttribute('d', d);
  for (const [k, v] of Object.entries(attrs)) el.setAttribute(k, v);
  return el;
}

/**
 * The Chiasm mark: two canes crossing, one over the other.
 *
 * The green cane is TWO paths and must stay that way. The alternative is a
 * single green stroke with the gold one laid over it plus a third stroke in
 * the background colour knocked out between them to fake the weave — which
 * only works if you know what colour the ground is. Here the ground changes
 * with the theme, so the green is broken at the crossing instead and nothing
 * has to be painted in the background's colour. The break points are computed,
 * not eyeballed: the canes cross at (32,32), and the gap clears it at
 * (25.64, 38.36) and (38.36, 25.64).
 *
 * A fresh element each call — an SVG node can live in one place only.
 */
export function nectendaMark(size = 24): SVGSVGElement {
  const el = svg('0 0 64 64', size, size, 'nectenda-mark');
  const g = document.createElementNS(SVG_NS, 'g');
  g.setAttribute('fill', 'none');
  g.setAttribute('stroke-width', '8');
  g.setAttribute('stroke-linecap', 'butt');
  g.setAttribute('stroke-linejoin', 'round');
  const vine = 'var(--nectenda-text-vine)';
  g.appendChild(path('M4 44 H20 L25.64 38.36', { stroke: vine }));
  g.appendChild(path('M38.36 25.64 L44 20 H60', { stroke: vine }));
  g.appendChild(path('M4 20 H20 L44 44 H60', { stroke: 'var(--nectenda-action-primary)' }));
  el.appendChild(g);
  return el;
}

/**
 * The wordmark, as drawn artwork rather than live text.
 *
 * It is Literata at one optical size, normalised and then corrected by hand —
 * kerning in seven places and a settled ct bind — so setting "Nectenda" in a
 * font would not reproduce it, and the plugin ships no fonts to set it with
 * anyway. Filled with currentColor so the surrounding text colour carries it.
 */
export function nectendaWordmark(height = 18): SVGSVGElement {
  // The source artwork sits on a baseline at y=0 and rises into negative y.
  const el = svg('1 -117 639 127', Math.round((height * 639) / 127), height, 'nectenda-wordmark');
  el.setAttribute('role', 'img');
  el.setAttribute('aria-label', 'Nectenda');
  el.removeAttribute('aria-hidden');
  el.appendChild(path(WORDMARK, { fill: 'currentColor' }));
  return el;
}

